import { VirtualFileSystem } from '../vfs';
import { LabContext } from '../context';

/**
 * Ensures standard Linux directory structure and essential configuration
 * files exist inside the Virtual File System for realistic Linux lab simulation.
 */
export function ensureLinuxFilesystem(ctx: LabContext): void {
  const vfs = ctx.vfs;

  // 1. Create standard root-level Linux directories
  const linuxDirs = [
    'C:\\etc',
    'C:\\var',
    'C:\\var\\log',
    'C:\\home',
    'C:\\home\\student',
    'C:\\tmp',
    'C:\\bin',
    'C:\\usr',
    'C:\\usr\\bin',
    'C:\\usr\\sbin',
    'C:\\usr\\local',
    'C:\\usr\\local\\bin',
    'C:\\opt',
    'C:\\root',
  ];

  for (const dir of linuxDirs) {
    if (!vfs.getNodeResult(dir)) {
      vfs.createDirectory(dir);
    }
  }

  // 2. Populate /etc/os-release
  if (!vfs.getNodeResult('C:\\etc\\os-release')) {
    vfs.createFile(
      'C:\\etc\\os-release',
      `NAME="Ubuntu"
VERSION="22.04.4 LTS (Jammy Jellyfish)"
ID=ubuntu
ID_LIKE=debian
PRETTY_NAME="Ubuntu 22.04.4 LTS"
VERSION_ID="22.04"
HOME_URL="https://www.ubuntu.com/"
SUPPORT_URL="https://help.ubuntu.com/"
BUG_REPORT_URL="https://bugs.launchpad.net/ubuntu/"`
    );
  }

  // 3. Populate /etc/hostname
  const host = ctx.computerName.toLowerCase().replace('desktop-', '');
  if (!vfs.getNodeResult('C:\\etc\\hostname')) {
    vfs.createFile('C:\\etc\\hostname', host);
  }

  // 4. Populate /etc/hosts
  if (!vfs.getNodeResult('C:\\etc\\hosts')) {
    vfs.createFile(
      'C:\\etc\\hosts',
      `127.0.0.1       localhost
127.0.1.1       ${host}.lab.polytechnic.ac.in   ${host}
192.168.1.1     gateway.lab.polytechnic.ac.in   router
8.8.8.8         dns.google                      dns`
    );
  }

  // 5. Populate /etc/resolv.conf
  if (!vfs.getNodeResult('C:\\etc\\resolv.conf')) {
    vfs.createFile(
      'C:\\etc\\resolv.conf',
      `# Generated by NetworkManager
nameserver 8.8.8.8
nameserver 8.8.4.4
search lab.polytechnic.ac.in`
    );
  }

  // 6. Populate /etc/passwd
  if (!vfs.getNodeResult('C:\\etc\\passwd')) {
    vfs.createFile(
      'C:\\etc\\passwd',
      `root:x:0:0:root:/root:/bin/bash
daemon:x:1:1:daemon:/usr/sbin:/usr/sbin/nologin
bin:x:2:2:bin:/bin:/usr/sbin/nologin
sys:x:3:3:sys:/dev:/usr/sbin/nologin
student:x:1000:1000:Student User,,,:/home/student:/bin/bash
sshd:x:110:65534::/run/sshd:/usr/sbin/nologin
systemd-network:x:101:102:systemd Network Management,,,:/run/systemd:/usr/sbin/nologin`
    );
  }

  // 7. Populate /etc/group
  if (!vfs.getNodeResult('C:\\etc\\group')) {
    vfs.createFile(
      'C:\\etc\\group',
      `root:x:0:
daemon:x:1:
bin:x:2:
sys:x:3:
adm:x:4:student
sudo:x:27:student
student:x:1000:
users:x:100:`
    );
  }

  // 8. Populate /etc/issue
  if (!vfs.getNodeResult('C:\\etc\\issue')) {
    vfs.createFile('C:\\etc\\issue', 'Ubuntu 22.04.4 LTS \\n \\l\n');
  }

  // 9. Populate ~/.bashrc and ~/.profile
  if (!vfs.getNodeResult('C:\\Users\\Student\\.bashrc')) {
    vfs.createFile(
      'C:\\Users\\Student\\.bashrc',
      `# ~/.bashrc: executed by bash(1) for non-login shells.
alias ll='ls -la'
alias la='ls -A'
alias l='ls -CF'
alias grep='grep --color=auto'
export PATH=$PATH:/usr/local/bin:/usr/bin:/bin`
    );
  }

  // 10. Populate /var/log/syslog and /var/log/auth.log
  if (!vfs.getNodeResult('C:\\var\\log\\syslog')) {
    vfs.createFile(
      'C:\\var\\log\\syslog',
      `Sep  8 06:25:01 sna25 systemd[1]: Starting Daily apt download activities...
Sep  8 06:25:03 sna25 systemd[1]: apt-daily.service: Deactivated successfully.
Sep  8 08:30:12 sna25 kernel: [    0.000000] Linux version 5.15.0-100-generic (buildd@lcy02-amd64-001)
Sep  8 08:30:14 sna25 systemd[1]: Started OpenBSD Secure Shell server.
Sep  8 08:30:15 sna25 systemd[1]: Started nginx - high performance web server.`
    );
  }
}

/**
 * Converts a Linux/POSIX path to a VFS internal path (resolving ~, /home, /etc, relative paths).
 */
export function toVfsPath(posixPath: string, currentVfsCwd: string): string {
  let p = posixPath.trim();
  if (!p) return currentVfsCwd;

  // Handle home directory ~
  if (p === '~' || p === '~/') {
    return 'C:\\Users\\Student';
  }
  if (p.startsWith('~/')) {
    return 'C:\\Users\\Student\\' + p.slice(2).replace(/\//g, '\\');
  }

  // Handle /home/student
  if (p.toLowerCase() === '/home/student' || p.toLowerCase() === '/home/student/') {
    return 'C:\\Users\\Student';
  }
  if (p.toLowerCase().startsWith('/home/student/')) {
    return 'C:\\Users\\Student\\' + p.slice('/home/student/'.length).replace(/\//g, '\\');
  }

  // If standing in C:\home and entering 'student'
  if (currentVfsCwd.toLowerCase().replace(/\\$/, '') === 'c:\\home' && (p.toLowerCase() === 'student' || p.toLowerCase() === 'student/')) {
    return 'C:\\Users\\Student';
  }

  // Handle /Users/Student
  if (p.toLowerCase() === '/users/student' || p.toLowerCase() === '/users/student/') {
    return 'C:\\Users\\Student';
  }
  if (p.toLowerCase().startsWith('/users/student/')) {
    return 'C:\\Users\\Student\\' + p.slice('/users/student/'.length).replace(/\//g, '\\');
  }

  // Root directory /
  if (p === '/') {
    return 'C:\\';
  }

  // Absolute paths starting with /
  if (p.startsWith('/')) {
    return 'C:' + p.replace(/\//g, '\\');
  }

  // If already a Windows path like C:\
  if (/^[a-zA-Z]:/.test(p)) {
    return p.replace(/\//g, '\\');
  }

  // Relative path against current VFS CWD
  return (currentVfsCwd.endsWith('\\') ? currentVfsCwd : currentVfsCwd + '\\') + p.replace(/\//g, '\\');
}

/**
 * Returns full POSIX path representation (e.g. /home/student instead of ~ for pwd and $PWD).
 */
export function toPosixFullPath(vfsPath: string): string {
  let p = vfsPath.replace(/\\/g, '/');
  if (/^[a-zA-Z]:/.test(p)) {
    p = p.substring(2);
  }
  if (!p) p = '/';

  if (p.toLowerCase() === '/users/student' || p.toLowerCase() === '/home/student') {
    return '/home/student';
  }
  if (p.toLowerCase().startsWith('/users/student/')) {
    return '/home/student' + p.substring('/users/student'.length);
  }
  if (p.toLowerCase().startsWith('/home/student/')) {
    return '/home/student' + p.substring('/home/student'.length);
  }
  return p;
}

/**
 * Formats a VFS path into a friendly POSIX path for display in prompts (collapsing /home/student to ~).
 */
export function toPosixPath(vfsPath: string): string {
  let p = vfsPath.replace(/\\/g, '/');
  if (/^[a-zA-Z]:/.test(p)) {
    p = p.substring(2);
  }
  if (!p) p = '/';

  // Normalize /Users/Student or /home/student to ~
  if (p.toLowerCase() === '/users/student' || p.toLowerCase() === '/home/student') {
    return '~';
  }
  if (p.toLowerCase().startsWith('/users/student/')) {
    return '~' + p.substring('/users/student'.length);
  }
  if (p.toLowerCase().startsWith('/home/student/')) {
    return '~' + p.substring('/home/student'.length);
  }
  return p;
}
